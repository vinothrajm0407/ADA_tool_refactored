def test_report_splits_fixed_from_still_to_fix():
    from backend.services.report_pdf_service import _build_full_scan_report_html, _split_fixed
    violations = [
        {"id": "image-alt", "impact": "critical", "help": "x", "nodes": [{"target": ["img"], "html": "<img>"}]},
        {"id": "label", "impact": "critical", "help": "x", "nodes": [{"target": ["#a"], "html": "<input id=a>"},
                                                                     {"target": ["#b"], "html": "<input id=b>"}]},
    ]
    proofs = [{"rule_id": "label", "selector": "#a", "created_at": "2026-11-19"},
              {"rule_id": "label", "selector": "#a", "created_at": "2026-11-18"},  # older duplicate
              {"rule_id": "image-alt", "selector": "img", "created_at": "2026-11-19"}]
    open_, fixed = _split_fixed(violations, proofs)
    assert [(v["id"], [n["target"] for n in v["nodes"]]) for v in open_] == [("label", [["#b"]])]
    assert len(fixed) == 2
    html = _build_full_scan_report_html("https://x", 80, violations, 10, "SCAN-1", None, proofs)
    assert "Still to fix (1)" in html and "Fixed (2)" in html and "1 issue still needs fixing." in html
    assert "A form field has no label" in html  # plain language, not axe's wording


def test_developer_table_lists_open_and_fixed_with_code_change():
    from backend.services.report_pdf_service import _build_full_scan_report_html
    violations = [{"id": "image-alt", "impact": "critical", "help": "Images must have alternative text",
                   "nodes": [{"target": ["img"], "html": "<img src=a.png>"}]},
                  {"id": "label", "impact": "critical", "help": "Form elements must have labels",
                   "nodes": [{"target": ["#e"], "html": "<input id=e>"}]}]
    proofs = [{"rule_id": "image-alt", "selector": "img", "help": "Images must have alternative text", "pr_url": "https://x/pull/1",
               "file": "docs/index.html:25", "code_before": "<img src=a.png>", "code_after": '<img src=a.png alt="A">'}]
    html = _build_full_scan_report_html("https://x", 80, violations, 10, "SCAN-1", None, proofs)
    table = html[html.index("Developer task list"):html.index("Still to fix (")]
    assert table.count("<tr style=") == 2 and ">Open<" in table and ">Fixed<" in table
    assert "docs/index.html:25" in table and "changed to" in table and "https://x/pull/1" in table
    assert table.count(">critical<") == 2  # fixed row takes severity from the scan when the proof has none
