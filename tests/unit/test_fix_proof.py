def test_announce_reads_like_a_screen_reader():
    assert fix_proof.announce('- button "Close dialog": x') == '"Close dialog", button'
    assert fix_proof.announce("- button:\n  - img") == "button — no accessible name"
    assert fix_proof.announce('- checkbox "Agree" [checked]') == '"Agree", checkbox, checked'
    assert fix_proof.announce('- heading "Hi" [level=1]') == '"Hi", heading, level 1'
    assert fix_proof.announce("- img").startswith("image — no name")
    assert fix_proof.announce("- paragraph: grey text") == '"grey text"'
    assert fix_proof.announce("- term: Owner\n- definition: Design team") == '"Owner", term'
    assert fix_proof.announce("").startswith("Nothing")


def test_pr_section_sits_above_footer():
    proof = {"selector": "button", "before_img": "https://x/b.jpg", "after_announce": '"Close", button',
             "before_announce": "button — no accessible name", "rescan": "Re-scanned.", "before_url": "https://site"}
    body = _with_proof("### Fix\n\nstuff\n\n---\nGenerated by ADA Auto-Fix", [proof])
    assert body.index("### Proof") < body.index("\n---\nGenerated")
    assert "![before](https://x/b.jpg)" in body and "_screenshot unavailable_" in body  # no after_img
    assert '"Close", button' in body
    assert _with_proof("body", [None]) == "body"


def _serve(root):
    srv = http.server.ThreadingHTTPServer(("127.0.0.1", 0), functools.partial(
        http.server.SimpleHTTPRequestHandler, directory=str(root)))
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    return srv, f"http://127.0.0.1:{srv.server_address[1]}"


@pytest.mark.timeout(90)
def test_capture_and_push_proof_end_to_end(tmp_path):
    """Real browser: before page has an unnamed button, after page names it;
    then the screenshots are pushed to an orphan branch of a real git remote."""
    before_dir, after_dir = tmp_path / "before", tmp_path / "after"
    before_dir.mkdir(); after_dir.mkdir()
    (before_dir / "index.html").write_text('<html lang="en"><title>T</title><button id="b"><svg width="20" height="20"></svg></button>')
    (after_dir / "index.html").write_text('<html lang="en"><title>T</title><button id="b" aria-label="Close dialog"><svg width="20" height="20"></svg></button>')
    s1, before_url = _serve(before_dir)
    s2, after_url = _serve(after_dir)
    try:
        proof = fix_proof.capture_proof(before_url + "/", after_url, {"id": "button-name"},
                                        {"html": "<button>", "target": ["#b"]})
    finally:
        s1.shutdown(); s2.shutdown()
    assert proof["before_announce"] == 'button — no name (a screen reader just says "button")'
    assert proof["after_announce"] == '"Close dialog", button'
    assert proof["before_screenshot"] and proof["after_screenshot"]

    remote, work = tmp_path / "remote.git", tmp_path / "work"
    subprocess.run(["git", "init", "-q", "--bare", str(remote)], check=True)
    subprocess.run(["git", "clone", "-q", str(remote), str(work)], check=True)
    (work / "app.js").write_text("code")

    def git(*args, extra_headers=False):
        subprocess.run(["git", "-c", "user.email=t@t", "-c", "user.name=t", *args], cwd=work, check=True, capture_output=True)

    git("add", "-A"); git("commit", "-m", "fix"); git("push", "origin", "HEAD:ada/fix/button-name-1")
    assert fix_proof.push_proof_branch(work, git, [proof], "ada/fix/button-name-1", "github", "o/r")
    files = subprocess.run(["git", "ls-tree", "--name-only", "ada-proof-button-name-1"], cwd=remote,
                           capture_output=True, text=True, check=True).stdout.split()
    assert files == ["after-1.jpg", "before-1.jpg"]  # orphan: no source files ride along
    assert proof["before_img"] == "https://github.com/o/r/blob/ada-proof-button-name-1/before-1.jpg?raw=true"


@pytest.mark.timeout(60)
def test_static_preview_serves_the_scanned_page_not_a_404(tmp_path):
    """Regression: http.server's "(http://127.0.0.1:PORT/)" banner used to give a
    preview URL ending in ")" — every static-site re-scan hit a 404 and passed."""
    from backend.services.auto_fix_service import build_and_preview, preview_page_url
    (tmp_path / "docs").mkdir()
    (tmp_path / "docs" / "index.html").write_text("<h1>home</h1>")
    (tmp_path / "docs" / "about.html").write_text("<h1>about</h1>")
    with build_and_preview(tmp_path) as url:
        assert not url.endswith(")")
        # GitHub Pages serves under /<repo>/, the static preview serves docs/ at /
        assert preview_page_url(url, "https://u.github.io/repo/about.html", "/repo/") == url.rstrip("/") + "/about.html"
        assert preview_page_url(url, "https://u.github.io/repo/", "/repo/") == url.rstrip("/") + "/"
        with pytest.raises(RuntimeError):
            preview_page_url(url.rstrip("/") + "/nope", "https://u.github.io/x.html", None)


